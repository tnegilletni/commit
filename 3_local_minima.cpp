//Дан прямоугольный массив цифр (карта высот 10х10). Нужно найти локальные минимумы (точки, которые меньше всех своих 
//четырех соседей вверх, вниз, влево, вправо и по диаганалям) (Массив: int matrix[10][10] = ... задавайте сразу в коде)

#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "ru_RU.UTF-8");
    int matrix[10][10] = {
        {5, 3, 4, 6, 7, 8, 9, 1, 2, 3},
        {4, 2, 5, 3, 6, 7, 8, 9, 1, 4},
        {6, 7, 1, 8, 2, 9, 3, 4, 5, 6},
        {9, 8, 7, 6, 5, 4, 3, 2, 1, 0},
        {1, 3, 5, 7, 9, 2, 4, 6, 8, 0},
        {2, 4, 6, 8, 0, 1, 3, 5, 7, 9},
        {9, 7, 5, 3, 1, 8, 6, 4, 2, 0},
        {0, 2, 4, 6, 8, 1, 3, 5, 7, 9},
        {1, 2, 3, 4, 5, 6, 7, 8, 9, 0},
        {9, 8, 7, 6, 5, 4, 3, 2, 1, 0}
    };

    cout << "Локальные минимумы:\n";

    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < 10; j++) {
            bool isMin = true;

            for (int di = -1; di <= 1; di++) {
                for (int dj = -1; dj <= 1; dj++) {
                    if (di == 0 && dj == 0) continue; 

                    int ni = i + di;
                    int nj = j + dj;

                    if (ni >= 0 && ni < 10 && nj >= 0 && nj < 10){
                        if (matrix[ni][nj] <= matrix[i][j]) {
                            isMin = false;
                        }
                    }
                }
            }

            if (isMin==true) {
                cout << "Значение " << matrix[i][j]
                     << " в позиции [" << i << "][" << j << "]\n";
            }
        }
    }

    return 0;
}